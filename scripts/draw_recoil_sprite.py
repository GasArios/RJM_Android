#!/usr/bin/env python3
"""Bake RJM's unrotated-at-runtime recoil and landing pixel cels."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'godot-lab'
SIZE = 24
PIVOT = SIZE // 2
COLS = 8

# Three hand drawn stages, facing east and northeast. Each band specifies
# two-dimensional, integer-aligned ink coverage, with no geometric stretching.
EAST = [
    [(-9, -8, -5, 5), (-8, -6, -6, 6), (-6, 7, -7, 6), (7, 9, -6, 5)],
    [(-7, -6, -6, 8), (-6, -4, -8, 10), (-4, 4, -9, 12), (4, 6, -8, 10), (6, 7, -6, 8)],
    [(-8, -7, -7, 7), (-7, -5, -8, 9), (-5, 5, -9, 9), (5, 7, -8, 8), (7, 8, -7, 7)],
]
NORTHEAST = [
    [(-8, -7, -7, 2), (-7, -4, -8, 5), (-4, -1, -9, 7), (-1, 5, -9, 8),
     (5, 8, -8, 7), (8, 10, -7, 4)],
    [(-11, -10, 2, 10), (-10, -8, -2, 11), (-8, -5, -5, 11), (-5, -1, -7, 10),
     (-1, 3, -9, 8), (3, 6, -10, 6), (6, 8, -10, 3), (8, 9, -9, -1)],
    [(-9, -8, -4, 6), (-8, -6, -6, 9), (-6, -3, -8, 9), (-3, 4, -9, 8),
     (4, 7, -9, 7), (7, 9, -8, 4)],
]
IDLE = [(-8, 8, -8, 8)]
LAND = [
    [(-3, -2, -8, 8), (-2, 0, -10, 10), (0, 7, -11, 11), (7, 8, -10, 10)],
    [(-5, -4, -8, 8), (-4, -2, -9, 9), (-2, 7, -10, 10), (7, 8, -9, 9)],
    [(-6, -5, -8, 8), (-5, 7, -9, 9), (7, 8, -8, 8)],
]


def ink(bands):
    return {(x, y) for y0, y1, x0, x1 in bands for y in range(y0, y1) for x in range(x0, x1)}


def turn_clockwise(cel):
    # Rotate the integer silhouette around the cell center during authoring.
    # Shading is reapplied afterwards, so light still comes from above.
    return {(-y-1, x) for x, y in cel}


def facing(phase, octant):
    if octant % 2:
        cel = ink(NORTHEAST[phase])
        quarter_turns = ((octant + 1) // 2) % 4
    else:
        cel = ink(EAST[phase])
        quarter_turns = octant // 2
    for _ in range(quarter_turns):
        cel = turn_clockwise(cel)
    return cel


def spans(cel):
    edges, bottom = [], 0
    for y in range(-PIVOT, PIVOT):
        row = sorted(x for x, v in cel if v == y)
        if not row:
            edges.append('AA')
            continue
        assert row == list(range(row[0], row[-1]+1))
        lo, hi = row[0]+PIVOT, row[-1]+PIVOT+1
        assert 0 <= lo < hi <= SIZE
        edges.append(chr(65+lo)+chr(65+hi))
        bottom = y+1
    return ''.join(edges), bottom


def paint(cel, index, paths):
    ox, oy = (index % COLS)*SIZE+PIVOT, (index // COLS)*SIZE+PIVOT
    assert all(-PIVOT <= x < PIVOT and -PIVOT <= y < PIVOT for x, y in cel)
    def color_at(x, y):
        if (x, y-1) not in cel or (x-1, y) not in cel:
            return '#c3efff'
        if (x, y+1) not in cel or (x+1, y) not in cel:
            return '#7acafd'
        if (x, y-2) not in cel:
            return '#65c8ff'
        if (x, y+2) not in cel:
            return '#2376cd'
        return '#3899f0'

    for y in range(-PIVOT, PIVOT):
        x = -PIVOT
        while x < PIVOT:
            if (x, y) not in cel:
                x += 1
                continue
            color = color_at(x, y)
            start = x
            x += 1
            while (x, y) in cel and color_at(x, y) == color:
                x += 1
            width = x - start
            paths.setdefault(color, []).append(f'M{ox+start} {oy+y}h{width}v1h{-width}z')


def main():
    frames = [facing(phase, octant) for phase in range(3) for octant in range(COLS)]
    frames += [ink(IDLE)] + [ink(stage) for stage in LAND]
    paths = {}
    for i, cel in enumerate(frames):
        paint(cel, i, paths)
    svg = '\n'.join(f'  <path fill="{c}" d="{" ".join(p)}"/>' for c, p in paths.items())
    (ROOT/'assets/recoil-cels.svg').write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" width="192" height="96" '
        'viewBox="0 0 192 96" shape-rendering="crispEdges">\n'+svg+'\n</svg>\n')
    rows, bottoms = zip(*(spans(cel) for cel in frames))
    data = 'extends RefCounted\n## Generated by scripts/draw_recoil_sprite.py.\n'
    data += 'const CELL := 24\nconst COLS := 8\n'
    data += 'const BOTTOM := [' + ', '.join(map(str, bottoms)) + ']\n'
    data += 'const SPANS := [\n'+''.join(f'\t"{row}",\n' for row in rows)+']\n'
    (ROOT/'src/recoil_cel_data.gd').write_text(data)


if __name__ == '__main__':
    main()
