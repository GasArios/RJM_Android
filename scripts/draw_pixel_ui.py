#!/usr/bin/env python3
"""Bake RJM's hand-drawn UI glyphs and masks onto a nearest-filtered atlas."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "godot-lab"
# Seven rows encoded left-to-right in five bits; unused outer columns
# are removed when setting the advances. All artwork below is original.
GLYPHS = {
    "A": "0e11111f111111", "B": "1e11111e11111e", "C": "0e11101010110e",
    "D": "1e11111111111e", "E": "1f10101e10101f", "F": "1f10101e101010",
    "G": "0e11101711110f", "H": "1111111f111111", "I": "0e04040404040e",
    "J": "0702020202120c", "K": "11121418141211", "L": "1010101010101f",
    "M": "111b1515111111", "N": "11191513111111", "O": "0e11111111110e",
    "P": "1e11111e101010", "Q": "0e11111115120d", "R": "1e11111e141211",
    "S": "0f10100e01011e", "T": "1f040404040404", "U": "1111111111110e",
    "V": "11111111110a04", "W": "11111115151b11", "X": "11110a040a1111",
    "Y": "11110a04040404", "Z": "1f01020408101f",
    "0": "0e11131519110e", "1": "040c040404040e", "2": "0e11010204081f",
    "3": "1e01010601011e", "4": "02060a121f0202", "5": "1f10101e01011e",
    "6": "0e10101e11110e", "7": "1f010204080808", "8": "0e11110e11110e",
    "9": "0e11110f01010e",
    "!": "04040404040004", "%": "19190204081313", "'": "04040800000000",
    "(": "02040808080402", ")": "08040202020408", "+": "0004041f040400",
    ",": "00000000000408", "-": "0000001f000000", ".": "00000000000004",
    "/": "01010204081010", ":": "00040000040000", "?": "0e110102040004",
}

paths = []


def rect(x, y, w, h=1):
    paths.append(f"M{x} {y}h{w}v{h}h{-w}z")


def disk(ox, oy, r, inner=0):
    # Sample the circumference at the centers of native atlas pixels.
    for y in range(-r, r):
        line = [x + ox + r for x in range(-r, r)
                if inner**2 <= (x + .5)**2 + (y + .5)**2 < r**2]
        i = 0
        while i < len(line):
            a = line[i]
            i += 1
            while i < len(line) and line[i] == line[i - 1] + 1:
                i += 1
            rect(a, oy + y + r, line[i - 1] - a + 1)


widths = ""
for k in range(32, 96):
    glyph = GLYPHS.get(chr(k))
    if glyph is None:
        widths += "3" if k == 32 else "0"
        continue
    rows = bytes.fromhex(glyph)
    assert len(rows) == 7 and max(rows) < 32
    grid = [(x, y) for y, row in enumerate(rows) for x in range(5) if row & (16 >> x)]
    left, right = min(x for x, _ in grid), max(x for x, _ in grid)
    widths += str(right - left + 2)  # include the one-pixel gap
    for x, y in grid:
        rect((k - 32) % 16 * 6 + x - left, (k - 32) // 16 * 8 + y, 1)

disk(0, 32, 50)
disk(100, 32, 50, 48)
disk(200, 32, 14)
disk(200, 60, 14, 12)
disk(228, 32, 9, 8)
disk(228, 50, 6, 4)
output = '<svg xmlns="http://www.w3.org/2000/svg" width="248" height="132" shape-rendering="crispEdges">\n'
output += f'<path fill="#fff" d="{" ".join(paths)}"/>\n</svg>\n'
(ROOT / "assets/pixel-ui.svg").write_text(output)
(ROOT / "src/pixel_glyphs.gd").write_text(
    f'extends RefCounted\n## Generated by scripts/draw_pixel_ui.py.\nconst ADVANCE := "{widths}"\n'
)
